/**
 * Build the two DSH halves of delta-dsh.
 *
 * - lib/index.js  Host half: one ESM bundle of the DSH adapter plus the vendored
 *   Delta hooks, with `h`/`Fragment` injected for the classic JSX the hooks use.
 * - lib/client.js Browser half: `window.__ModuleLoader__.load({id, factory})`
 *   exactly as the Harness Client module system expects; it is copied verbatim
 *   from src/client.js because the factory receives `require` from the loader.
 *
 * Run with: node scripts/build.mjs
 */
import { build } from 'esbuild'
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const plugin = join(here, '..')
const lib = join(plugin, 'lib')
const jsx = join(plugin, 'vendor', 'jsx.js')

/** The element constructors the vendored hooks' JSX resolves against. */
const BANNER = `// delta-dsh Host half — generated by scripts/build.mjs; edit src/ or vendor/delta/ instead.\n`

await mkdir(lib, { recursive: true })

await build({
  entryPoints: [join(plugin, 'src', 'index.js')],
  outfile: join(lib, 'index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  jsx: 'transform',
  jsxFactory: 'h',
  jsxFragment: 'Fragment',
  inject: [jsx],
  banner: { js: BANNER },
  sourcemap: false,
  logLevel: 'info',
})

/**
 * Inline the browser-side helper modules into the wrapper: the Client module
 * system loads one self-contained file, so it cannot import siblings. Each
 * helper stays an ordinary ESM module for its unit test; the build strips its
 * exports and substitutes the concatenation at the wrapper's placeholder.
 */
const HELPERS = ['band-i18n.js', 'band-visibility.js']
const inlined = []
for (const helper of HELPERS) {
  const source = (await readFile(join(plugin, 'src', helper), 'utf8')).replace(/^export /gm, '').trim()
  inlined.push(source.split('\n').map((line) => `    ${line}`).join('\n'))
}
const client = await readFile(join(plugin, 'src', 'client.js'), 'utf8')
const placeholder = '    /*__BAND_HELPERS__*/'
if (!client.includes(placeholder)) throw new Error('src/client.js is missing the band helpers placeholder')
await writeFile(join(lib, 'client.js'), client.replace(placeholder, inlined.join('\n\n')), 'utf8')
console.log(`lib/client.js built from src/client.js + ${HELPERS.join(', ')}`)
